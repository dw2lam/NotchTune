export const spriteSVG = (grid: number[][]): string => {
  let rects = '';
  grid.forEach((row, y) =>
    row.forEach((v, x) => {
      if (v) rects += `<rect x="${x}" y="${y}" width="1" height="1"/>`;
    })
  );
  return `<svg viewBox="0 0 9 9" shape-rendering="crispEdges" fill="#f1ead9" xmlns="http://www.w3.org/2000/svg">${rects}</svg>`;
};
